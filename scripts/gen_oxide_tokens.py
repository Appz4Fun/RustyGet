"""Generate webui/oxide.css from docs/design-system/oxide.json and check its contrast.

Usage: python3 scripts/gen_oxide_tokens.py
       python3 scripts/gen_oxide_tokens.py --check   (exit 1 if oxide.css is stale,
                                                       a contrast pair fails, or the
                                                       web UI mapping misses a token)
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'docs', 'design-system', 'oxide.json')
WEBUI_TOKENS = os.path.join(ROOT, 'docs', 'design-system', 'tokens.json')
TARGET = os.path.join(ROOT, 'webui', 'oxide.css')


def luminance(hex_color):
	value = hex_color.lstrip('#')
	channels = [int(value[i:i + 2], 16) / 255 for i in (0, 2, 4)]
	linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
	return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def ratio(fg, bg):
	high, low = sorted((luminance(fg), luminance(bg)), reverse=True)
	return (high + 0.05) / (low + 0.05)


def check_contrast(oxide):
	failures = []
	palette = oxide['palette']
	for rule in oxide['contrast']:
		for theme in oxide['themes']:
			for ground in rule['on']:
				value = ratio(palette[rule['fg']][theme], palette[ground][theme])
				if value < rule['min']:
					failures.append('%s on %s (%s): %.2f:1, needs %.1f:1' % (rule['fg'], ground, theme, value, rule['min']))
	return failures


def resolve(oxide, value, theme):
	if isinstance(value, dict):
		value = value[theme]
	if value in oxide['palette']:
		return 'var(--%s)' % value
	if value.startswith('{type.') and value.endswith('}'):
		return oxide['type']['families'][value[6:-1]]
	return value


def generate(oxide):
	out = [
		'/* Oxide, the RustyGet design system - generated by scripts/gen_oxide_tokens.py',
		'   from docs/design-system/oxide.json. Do not edit by hand.',
		'   Load after tokens.css: it sets the Oxide palette and points the web UI tokens at it. */',
		'',
	]
	mapping = {k: v for k, v in oxide['webui'].items() if not k.startswith('_')}
	# a web UI token that shares its palette name (on-accent) is already set by the palette;
	# writing "--x: var(--x)" would be a cycle that leaves it unset
	mapping = {k: v for k, v in mapping.items() if k != v}
	themed = {k: v for k, v in mapping.items() if isinstance(v, dict) or v in oxide['palette']}
	# dark first: its block also carries :root, which has the same specificity as
	# [data-theme="light"], so the light block must come after it to win
	for theme in sorted(oxide['themes'], key=lambda t: t != 'dark'):
		selector = ':root,\n[data-theme="dark"]' if theme == 'dark' else '[data-theme="light"]'
		out.append(selector + ' {')
		out.append('\tcolor-scheme: %s;' % theme)
		for name, token in oxide['palette'].items():
			out.append('\t--%s: %s;' % (name, token[theme]))
		for name, token in oxide['shadow'].items():
			out.append('\t--%s: %s;' % (name, token[theme]))
		out.append('')
		for name, value in themed.items():
			out.append('\t--%s: %s;' % (name, resolve(oxide, value, theme)))
		out += ['}', '']
	out.append(':root {')
	for name, value in oxide['radius'].items():
		out.append('\t--%s: %s;' % (name, value))
	for name, value in oxide['layout'].items():
		out.append('\t--%s: %s;' % (name, value))
	for name, value in mapping.items():
		if name not in themed:
			out.append('\t--%s: %s;' % (name, resolve(oxide, value, 'light')))
	out.append('}')
	return '\n'.join(out) + '\n'


def main():
	parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
	parser.add_argument('--check', action='store_true', help='fail if webui/oxide.css is stale or a check fails')
	args = parser.parse_args()
	with open(SOURCE, encoding='utf-8') as source:
		oxide = json.load(source)
	with open(WEBUI_TOKENS, encoding='utf-8') as source:
		webui = json.load(source)
	problems = check_contrast(oxide)
	color_names = [t['name'] for t in webui['color']['tokens']] + [t['name'] for t in webui['shadow']['tokens']]
	problems += ['web UI token --%s has no Oxide mapping' % n for n in color_names if n not in oxide['webui']]
	css = generate(oxide)
	if args.check:
		with open(TARGET, encoding='utf-8') as target:
			if target.read() != css:
				problems.append('webui/oxide.css is stale: run scripts/gen_oxide_tokens.py')
		for problem in problems:
			print(problem)
		if problems:
			return 1
		print('webui/oxide.css is up to date and every contrast pair passes')
		return 0
	for problem in problems:
		print('warning: ' + problem)
	with open(TARGET, 'w', encoding='utf-8') as target:
		target.write(css)
	print('wrote webui/oxide.css')
	return 1 if problems else 0


if __name__ == '__main__':
	sys.exit(main())
